import { build } from 'esbuild';
import { resolve, join, dirname } from 'node:path';
import { pathToFileURL } from 'node:url';
import { writeFile, mkdir, readFile, copyFile, rm } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { readRealtimePins, reviewRealtimeSource, assertRealtimeSourceStable } from './realtime-reviewed-sources.mjs';
const root = resolve(import.meta.dirname, '..');
export async function buildRealtimeOperator({ projectRoot = root, relayswarmRoot = resolve(projectRoot, '../relayswarm'),
  nativeRoot = resolve(relayswarmRoot, 'target/realtime-native'), allowWorkingTree = false } = {}) {
  const pins = await readRealtimePins(join(projectRoot, 'realtime-sources.json'));
  const selection = { directory: relayswarmRoot, repository: 'relayswarm', revision: pins.relayswarm, allowWorkingTree };
  const before = await reviewRealtimeSource(selection);
  const directory = join(projectRoot, 'dist/realtime-runtime');
  // Source preparation is explicit. Building this wrapper never fetches an
  // alternative binary or falls back to an npm platform prebuild.
  const { readPreparedNativeRealtime } = await import(pathToFileURL(join(relayswarmRoot, 'scripts/build-native-realtime.mjs')).href);
  const prepared = await readPreparedNativeRealtime(nativeRoot);
  if (prepared.receipt.bindingVersion !== '0.33.4' || prepared.receipt.libraryVersion !== '0.24.5-forgesworn-turn-close.1'
    || prepared.receipt.platform !== process.platform || prepared.receipt.arch !== process.arch
    || prepared.receipt.sourceModified !== true) throw new Error('Unsupported prepared native realtime build');
  await mkdir(directory, { recursive: true });
  await build({ entryPoints: [join(relayswarmRoot, 'src/node/native-realtime.mjs')], bundle: true, platform: 'node', format: 'esm',
    legalComments: 'inline', outfile: join(directory, 'native-backend.mjs') });
  await build({ entryPoints: [join(projectRoot, 'server/realtime-forwarder.ts')], bundle: true, platform: 'node', format: 'esm',
    outfile: join(projectRoot, 'dist/realtime-forwarder.mjs') });
  const sha = async path => createHash('sha256').update(await readFile(path)).digest('hex');
  const nativeAssets = {};
  for (const name of new Set([...prepared.files, 'native-addon.json'])) {
    if (!/^(?:native-addon\.(?:node|json)|SOURCE_NOTICE\.txt|(?:LICENSES|patches)\/[A-Za-z0-9_.-]+)$/.test(name)
      || name.endsWith('/.') || name.endsWith('/..')) throw new Error('Invalid prepared native output name');
    const destination = join(directory, 'native', name);
    await mkdir(dirname(destination), { recursive: true });
    if (name === 'native-addon.json') await writeFile(destination, JSON.stringify(prepared.receipt, null, 2) + '\n');
    else await copyFile(join(nativeRoot, name), destination);
    const hash = await sha(destination);
    if (name !== 'native-addon.json' && hash !== prepared.receipt.files[name]) throw new Error('Prepared native output changed during packaging');
    nativeAssets['native/' + name] = hash;
  }
  const source = await reviewRealtimeSource(selection);
  assertRealtimeSourceStable(before, source);
  // Retire only the two notices generated by the earlier stock-native build.
  // Its "unmodified" declaration must not accompany this patched sidecar.
  for (const name of ['NODE_DATA_CHANNEL_LICENSE', 'NATIVE_SOURCE_NOTICE.txt']) await rm(join(directory, name), { force: true });
  const receipt = { kind: 'node-datachannel-native-patched', version: prepared.receipt.bindingVersion,
    libraryVersion: prepared.receipt.libraryVersion, role: 'initiator-only', license: 'MPL-2.0', native: prepared.receipt, source,
    facadeSha256: await sha(join(directory, 'native-backend.mjs')), bundleSha256: await sha(join(projectRoot, 'dist/realtime-forwarder.mjs')) };
  await writeFile(join(directory, 'operator-backend.json'), JSON.stringify(receipt, null, 2) + '\n');
  try {
    const path = join(directory, 'manifest.json'), manifest = JSON.parse(await readFile(path, 'utf8'));
    manifest.sources = [...(manifest.sources ?? []).filter(entry => entry.repository !== 'relayswarm'), source];
    manifest.nativeAssets = { ...nativeAssets, 'native-backend.mjs': await sha(join(directory, 'native-backend.mjs')) };
    await writeFile(path, JSON.stringify(manifest, null, 2) + '\n');
  } catch (error) { if (error.code !== 'ENOENT') throw error; }
}
if (process.argv[1] && resolve(process.argv[1]) === import.meta.filename) {
  const args = process.argv.slice(2), i = args.indexOf('--relayswarm-root');
  if (i >= 0 && (!args[i + 1] || args[i + 1].startsWith('--'))) throw new Error('Realtime build option requires a value');
  await buildRealtimeOperator({ ...(i >= 0 ? { relayswarmRoot: resolve(args[i + 1]) } : {}), allowWorkingTree: args.includes('--allow-working-tree') });
}
