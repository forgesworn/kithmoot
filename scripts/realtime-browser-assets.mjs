import { createHash } from 'node:crypto';
import { copyFile, lstat, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { basename, join } from 'node:path';

const code = ['transport.mjs', 'sapflow.mjs', 'sapflow_realtime_bg.wasm'];
const notices = ['SAPFLOW_LICENSE', 'SAPFLOW_THIRD_PARTY_LICENSES.txt', 'RELAYSWARM_LICENSE'];
const ownedNative = ['native-backend.mjs', 'operator-backend.json', 'NATIVE_SOURCE_NOTICE.txt', 'NODE_DATA_CHANNEL_LICENSE'];
const browserNames = new Set([...code, ...notices, 'manifest.json']);
async function regular(path, required = false) {
  try {
    const info = await lstat(path);
    if (info.isSymbolicLink() || !info.isFile()) throw new Error('Realtime browser output must be a regular file');
  } catch (error) { if (required || error.code !== 'ENOENT') throw error; }
}

/** Publish only browser code, WASM, licences and its browser manifest. Native
 * sidecars never enter the PWA tree or its service-worker precache. */
export async function copyRealtimeBrowserAssets(source, destination) {
  const manifest = JSON.parse(await readFile(join(source, 'manifest.json'), 'utf8'));
  for (const name of [...code, ...notices]) {
    await regular(join(source, name), true);
    if (code.includes(name)) {
      const hash = createHash('sha256').update(await readFile(join(source, name))).digest('hex');
      if (hash !== manifest.assets?.[name]) throw new Error('Realtime browser asset differs from its manifest');
    }
  }
  try { if ((await lstat(destination)).isSymbolicLink()) throw new Error('Realtime browser output cannot be a symbolic link'); }
  catch (error) { if (error.code !== 'ENOENT') throw error; }
  let previous;
  try { previous = JSON.parse(await readFile(join(destination, 'manifest.json'), 'utf8')); }
  catch (error) { if (error.code !== 'ENOENT' && !(error instanceof SyntaxError)) throw error; }
  await mkdir(destination, { recursive: true });
  for (const name of [...code, ...notices, 'manifest.json']) await regular(join(destination, name));
  for (const name of [...code, ...notices]) await copyFile(join(source, name), join(destination, name));
  // Only names explicitly generated by this task or recorded as native assets
  // in its manifests are retired. Preserve every unrelated public file.
  for (const name of new Set([...ownedNative, ...Object.keys(manifest.nativeAssets ?? {}), ...Object.keys(previous?.nativeAssets ?? {})])) {
    if (name && name !== '.' && name !== '..' && name === basename(name) && !name.includes('\\') && !browserNames.has(name)) {
      await rm(join(destination, name), { force: true });
    }
  }
  const browserManifest = { format: manifest.format, sources: manifest.sources,
    assets: Object.fromEntries(code.map(name => [name, manifest.assets[name]])) };
  await writeFile(join(destination, 'manifest.json'), JSON.stringify(browserManifest, null, 2) + '\n');
}
