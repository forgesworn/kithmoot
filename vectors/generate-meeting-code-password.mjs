#!/usr/bin/env node
// Generates vectors/meeting-code-password-v1.json: one meeting code password
// envelope (docs/meeting-codes.md, "Password") from fixed inputs, with its
// intermediates, so a second implementation (Android) can reproduce the
// bytes and find which step differs when it does not.
//
// Built with node:crypto, not the app's WebCrypto code, so the vector and
// app/src/meeting-codes.ts are two implementations checked against each
// other by vectors/meeting-code-password-v1.test.ts.
//
//   node vectors/generate-meeting-code-password.mjs
import { createCipheriv, createHash, pbkdf2Sync } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const listText = readFileSync(join(here, '..', 'app', 'src', 'meeting-code-words-en-v1.txt'), 'utf8')
const list = listText.split('\n')

const indices = [0, 2047, 1024, 777]
const words = indices.map((i) => list[i]).join(' ')
const code = 'K7M2Q9TX'
const expires = 1792000000
const link = 'https://kithmoot.forgesworn.dev/j/#r=KITHMOOT-VECTOR-ROOM&i=fixed-invitation-0001'
const salt = Buffer.from([...Array(16).keys()])
const nonce = Buffer.from([...Array(12).keys()].map((i) => 0xa0 + i))
const iterations = 600000

const additionalData = `kithmoot-meeting-code/v1:${code}:${expires}`
const plaintext = JSON.stringify({ v: 1, link })
const key = pbkdf2Sync(Buffer.from(words, 'utf8'), salt, iterations, 32, 'sha256')
const cipher = createCipheriv('aes-256-gcm', key, nonce)
cipher.setAAD(Buffer.from(additionalData, 'utf8'))
const ciphertext = Buffer.concat([cipher.update(Buffer.from(plaintext, 'utf8')), cipher.final(), cipher.getAuthTag()])

const vector = {
  description:
    'KithMoot meeting code password envelope v1 (docs/meeting-codes.md, "Password"). ' +
    'key = PBKDF2-HMAC-SHA256(password = UTF-8 canonical words, salt, iterations, 32 bytes); ' +
    'ciphertext = AES-256-GCM(key, nonce, additionalData = UTF-8 aad, UTF-8 plaintext) with the 16-byte tag appended; ' +
    'envelope fields are base64url without padding. Generated by vectors/generate-meeting-code-password.mjs; never hand-edited.',
  wordList: {
    name: 'foregather en-v1',
    count: list.length,
    sha256: createHash('sha256').update(listText).digest('hex'),
  },
  input: {
    wordIndices: indices,
    words,
    typedVariants: [words.toUpperCase(), `  ${words.replaceAll(' ', '-')} `, words.replaceAll(' ', ',\t ')],
    code,
    expires,
    link,
    saltHex: salt.toString('hex'),
    nonceHex: nonce.toString('hex'),
    iterations,
  },
  intermediate: {
    passwordUtf8Hex: Buffer.from(words, 'utf8').toString('hex'),
    additionalData,
    plaintext,
    keyHex: key.toString('hex'),
    ciphertextHex: ciphertext.toString('hex'),
  },
  envelope: {
    v: 1,
    salt: salt.toString('base64url'),
    nonce: nonce.toString('base64url'),
    ciphertext: ciphertext.toString('base64url'),
  },
}

writeFileSync(join(here, 'meeting-code-password-v1.json'), `${JSON.stringify(vector, null, 2)}\n`)
