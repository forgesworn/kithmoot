test('shutdown synchronously refuses all new endpoint work and repeated stops join actual settlement', async ({ context }) => {
  const page = await fixture(context)
  await page.evaluate("E.workflow('setup')")
  await page.evaluate("E.configure('stop'); void(window.work = E.stopRace())")
  await expect.poll(async () => page.evaluate('E.status()')).toMatchObject({ reached: true, occupied: true })
  const before = await page.evaluate('E.status()')
  for (const method of ['resume','pair','request','socket','carrier']) expect(await page.evaluate(method => (window as any).E.duringStop(method), method)).toBe(false)
  await page.evaluate('window.stopEnded = false; void(window.repeatStop = E.stopAgain().then(() => { window.stopEnded = true }))')
  expect(await page.evaluate('window.stopEnded')).toBe(false)
  expect(await page.evaluate('E.status()')).toEqual(before)
  await page.evaluate('E.releaseWork()')
  expect(await page.evaluate('window.work')).toMatchObject({ state: 'active' })
  await page.evaluate('window.repeatStop')
  expect(await page.evaluate('window.stopEnded')).toBe(true)
  expect((await page.evaluate('navigator.locks.query()') as any).held).toEqual([])
})
