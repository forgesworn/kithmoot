test('two concrete endpoint owners cannot overlap native ownership or silently change the saved seed', async ({ context }) => {
  const first = await fixture(context), second = await fixture(context)
  await first.evaluate("E.workflow('setup')")
  await first.evaluate("E.configure('stop'); void(window.work = E.stopRace())")
  await expect.poll(async () => first.evaluate('E.status()')).toMatchObject({ reached: true })
  await expect(second.evaluate('E.workflow()')).rejects.toThrow()
  expect(await second.evaluate('E.status()')).toMatchObject({ starts: 0, occupied: false })
  const seed = (await first.evaluate('E.status()') as any).seed
  await first.evaluate('E.releaseWork()'); await first.evaluate('window.work')
  expect(await second.evaluate('E.workflow()')).toMatchObject({ state: 'active' })
  expect(await second.evaluate('E.status()')).toMatchObject({ starts: 1, stops: 1, seed })
})
