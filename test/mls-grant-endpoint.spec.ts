import { test, expect, type BrowserContext } from '@playwright/test'
import { build } from 'esbuild'
const origin = 'https://mls-grant-endpoint.kithmoot.test'
let bundle: string
test.beforeAll(async () => { bundle = (await build({ entryPoints: ['test/mls-grant-endpoint.browser-entry.ts'], bundle: true, write: false, format: 'iife', globalName: 'E', define: { 'import.meta.env.BASE_URL': '"/"' } })).outputFiles[0].text })
async function fixture(context: BrowserContext) {
  await context.route(origin + '/**', route => route.fulfill({ contentType: 'text/html', body: `<script>${bundle}</script>` }))
  const page = await context.newPage(); await page.goto(origin); return page
}
test('dedicated endpoint refuses unprepared use before starting or accessing its seed custody', async ({ context }) => {
  const page = await fixture(context)
  expect(await page.evaluate('E.unprepared()')).toBe(false)
  expect(await page.evaluate('E.status()')).toMatchObject({ starts: 0 })
  expect(await page.evaluate('indexedDB.databases()')).toEqual([])
})
test('dedicated seed and route survive foreground shutdown without touching ordinary endpoint custody', async ({ context }) => {
  const page = await fixture(context)
  const result = await page.evaluate("E.workflow('setup')") as any
  expect(result.state).toBe('active')
  const state = await page.evaluate('E.status()') as any
  expect(await page.evaluate('E.inspect()')).toMatchObject({ key: true, extractable: false, record: true })
  expect(await page.evaluate('E.saved()')).toEqual({ state: 'active', value: [result.value] })
  expect(await page.evaluate('E.status()')).toMatchObject({ starts: 1, stops: 1 })
  expect(await page.evaluate('E.workflow()')).toEqual(result)
  expect(await page.evaluate('E.status()')).toMatchObject({ seed: state.seed, starts: 2, stops: 2, occupied: false })
  expect((await page.evaluate('indexedDB.databases()') as any[]).map(item => item.name).sort()).toEqual(['kithmoot-vmls-grant-link-v1','kithmoot-vmls-grants-v1'])
  expect((await page.evaluate('navigator.locks.query()') as any).held).toEqual([])
})
for (const mode of ['quiet','tor-only']) test(`${mode} permits local dedicated route listing but refuses endpoint starts`, async ({ context }) => {
  const page = await fixture(context)
  const setup = await page.evaluate("E.workflow('setup')") as any
  await page.evaluate(mode => (window as any).E.configure('', mode), mode)
  expect(await page.evaluate('E.saved()')).toEqual({ state: 'active', value: [setup.value] })
  await expect(page.evaluate('E.workflow()')).rejects.toThrow('unavailable')
  expect(await page.evaluate('E.status()')).toMatchObject({ starts: 1, stops: 1, occupied: false })
})
for (const phase of ['start','pair','request','socket','signer','stop']) test(`late ${phase} retains endpoint ownership and foreground settlement until its actual promise ends`, async ({ context }) => {
  const page = await fixture(context)
  await page.evaluate("E.workflow('setup')")
  const before = await page.evaluate('E.inspect()')
  await page.evaluate(phase => {
    const w = window as any
    w.E.configure(phase)
    w.work = w.E.workflow(phase === 'pair' ? 'pair' : phase === 'request' ? 'request' : phase === 'socket' || phase === 'signer' ? 'publish' : 'resume')
      .then((value: unknown) => ({ value }), (error: Error) => ({ error: error.message }))
  }, phase)
  await expect.poll(async () => page.evaluate('E.status()')).toMatchObject({ reached: true, occupied: true })
  await page.evaluate('E.invalidate(); window.ended = false; void E.settled().then(() => { window.ended = true })')
  expect(await page.evaluate('window.ended')).toBe(false)
  expect(await page.evaluate('E.workflow()')).toEqual({ state: 'busy' })
  expect((await page.evaluate('navigator.locks.query()') as any).held.some((lock: any) => lock.name === 'kithmoot-vmls-grant-link-v1')).toBe(true)
  expect(await page.evaluate('E.status()')).toMatchObject({ publications: 0 })
  await page.evaluate('E.releaseWork()')
  expect(await page.evaluate('window.work')).toEqual({ value: { state: 'interrupted' } })
  await page.evaluate('E.settled()')
  expect(await page.evaluate('window.ended')).toBe(true)
  expect(await page.evaluate('E.inspect()')).toEqual(before)
  expect((await page.evaluate('navigator.locks.query()') as any).held).toEqual([])
})
