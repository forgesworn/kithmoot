for (const operation of ['read','put'] as const) {
  for (const invalidation of ['abort','predicate','none','throw'] as const) test(`floated ${operation} crypto retains scope and actual settlement through ${invalidation}`, async ({ context }) => {
    const page = await fixture(context)
    await page.evaluate('G.foregroundRead()')
    const before = await page.evaluate('G.rawSummary()')
    await page.evaluate(({ operation, fail }) => {
      const w = window as any; w.ended = false
      w.work = w.G.foregroundFloated(operation, 'crypto', fail).then((result: unknown) => ({ result }), (error: Error) => ({ error: error.message }))
      w.G.foregroundSettled().then(() => { w.ended = true })
    }, { operation, fail: invalidation === 'throw' })
    await expect.poll(async () => page.evaluate('G.foregroundStatus()')).toMatchObject({ phaseReached: true, occupied: true })
    // Capture after the asynchronous fixture has entered the real owner.
    await page.evaluate('window.ended = false; void G.foregroundSettled().then(() => { window.ended = true })')
    if (invalidation === 'abort') await page.evaluate('G.invalidateForeground()')
    if (invalidation === 'predicate') await page.evaluate('G.changeForegroundPredicate()')
    expect(await page.evaluate('window.ended')).toBe(false)
    expect(await page.evaluate('G.foregroundRead()')).toEqual({ state: 'busy' })
    await page.evaluate('G.releaseForegroundWork()')
    const result = await page.evaluate('window.work')
    expect(result).toEqual(invalidation === 'throw' ? { error: 'Floated callback refused' }
      : { result: invalidation === 'none' ? { state: 'active', value: 'callback returned' } : { state: 'interrupted' } })
    await page.evaluate('G.foregroundSettled()')
    expect(await page.evaluate('window.ended')).toBe(true)
    if (operation === 'read' || invalidation !== 'none') expect(await page.evaluate('G.rawSummary()')).toEqual(before)
    else expect(await page.evaluate('G.inspect()')).toMatchObject({ value: { records: [{ state: 'active' }] } })
  })
  for (const invalidation of ['abort','predicate'] as const) test(`queued normal ${operation} refuses ${invalidation} without stale storage effects`, async ({ context }) => {
    const page = await fixture(context)
    await page.evaluate('G.foregroundRead()')
    const before = await page.evaluate('G.rawSummary()')
    await page.evaluate(operation => { const w = window as any; w.work = w.G.foregroundFloated(operation, 'lock') }, operation)
    await expect.poll(async () => (await page.evaluate('navigator.locks.query()') as any).pending.some((lock: any) => lock.name === 'kithmoot-vmls-grants-v1')).toBe(true)
    await page.evaluate(invalidation === 'abort' ? 'G.invalidateForeground()' : 'G.changeForegroundPredicate()')
    if (invalidation === 'abort') {
      expect(await page.evaluate('window.work')).toEqual({ state: 'interrupted' })
      expect((await page.evaluate('navigator.locks.query()') as any).pending.some((lock: any) => lock.name === 'kithmoot-vmls-grants-v1')).toBe(false)
    } else expect(await page.evaluate('G.foregroundRead()')).toEqual({ state: 'busy' })
    await page.evaluate('G.releaseForegroundWork()')
    expect(await page.evaluate('window.work')).toEqual({ state: 'interrupted' })
    expect(await page.evaluate('G.rawSummary()')).toEqual(before)
  })
}
