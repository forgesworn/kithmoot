"""Original procedural drawings for exercising learning, NOT real-face data.

No downloads, fonts, stock images, real identities or third-party generators.
Good scores here establish plumbing only. They cannot qualify a camera model.
"""

import argparse
import json
import random
from pathlib import Path

from PIL import Image, ImageDraw

from .data import digest


def generate(root: Path, count: int = 30, seed: int = 18) -> Path:
    if root.exists():
        raise ValueError("Use a new data directory; existing captures must not be overwritten")
    root.mkdir(parents=True)
    evidence = root / "rights.txt"
    evidence.write_text("Original procedural KithMoot drawings, generated by synthetic.py.\n"
                        "No real subjects or external assets. Project-owned; MIT model weights permitted.\n"
                        "Synthetic smoke data only; no camera qualification value.\n")
    rng = random.Random(seed)
    records = []
    for split in ("train", "validation", "test"):
        for index in range(count if split == "train" else max(4, count // 3)):
            width, height = 160, 96
            base = tuple(rng.randrange(20, 160) for _ in range(3))
            reference = Image.new("RGB", (width, height), base)
            lines = ImageDraw.Draw(reference)
            for _ in range(12):
                x, y = rng.randrange(width), rng.randrange(height)
                lines.rectangle((x, y, min(width, x + rng.randrange(2, 30)), min(height, y + 15)),
                                fill=tuple(rng.randrange(20, 180) for _ in range(3)))
            rgb = reference.copy()
            alpha = Image.new("L", (width, height), 0)
            objects = Image.new("L", (width, height), 0)
            image, matte, held = ImageDraw.Draw(rgb), ImageDraw.Draw(alpha), ImageDraw.Draw(objects)
            faces = []
            subjects = []
            people = rng.randrange(4)
            for person in range(people):
                # Separate columns avoid ambiguous face-centre collisions.
                cx = int((person + 0.5) * width / max(people, 1)) + rng.randrange(-4, 5)
                cy = rng.randrange(22, 42)
                fw, fh = rng.randrange(15, 25), rng.randrange(22, 32)
                box = (cx - fw // 2, cy - fh // 2, cx + fw // 2, cy + fh // 2)
                skin = rng.choice(((233, 189, 156), (146, 87, 52), (82, 51, 38), (190, 124, 84)))
                body = [(cx - fw // 2, cy + fh // 2), (cx + fw // 2, cy + fh // 2),
                        (min(width - 1, cx + fw), height - 1), (max(0, cx - fw), height - 1)]
                image.polygon(body, fill=tuple(rng.randrange(60, 250) for _ in range(3)))
                matte.polygon(body, fill=255)
                image.ellipse(box, fill=skin)
                matte.ellipse(box, fill=255)
                for eye in (-fw // 5, fw // 5):
                    image.ellipse((cx + eye - 1, cy - 4, cx + eye + 1, cy - 2), fill=(10, 12, 15))
                image.line((cx - 3, cy + 5, cx + 3, cy + 5), fill=(70, 30, 30), width=1)
                faces.append([box[0] / width, box[1] / height,
                              (box[2] - box[0]) / width, (box[3] - box[1]) / height])
                subjects.append(f"synthetic-{split}-{index}-{person}")
                if rng.random() < 0.8:
                    left = max(0, cx - rng.randrange(8, 16))
                    obj = (left, min(height - 18, cy + fh), min(width - 1, left + rng.randrange(12, 24)), height - 10)
                    image.rectangle(obj, fill=tuple(rng.randrange(256) for _ in range(3)))
                    matte.rectangle(obj, fill=255)
                    held.rectangle(obj, fill=255)
            row = {"id": f"{split}-{index}", "scope": "general", "split": split,
                   "synthetic": True, "subjects": subjects, "scene": f"scene-{split}-{index}",
                   "sequence": f"sequence-{split}-{index}", "faces": faces, "faces_complete": True,
                   "foreground_includes_held_objects": True,
                   "rights": {"licence": "PROJECT-OWNED", "training": True, "commercial": True,
                              "mit_weights": True, "evidence": evidence.name,
                              "evidence_sha256": digest(evidence)}}
            for name, picture in (("rgb", rgb), ("alpha", alpha), ("reference", reference), ("held_objects", objects)):
                path = root / f"{split}-{index}-{name}.png"
                picture.save(path)
                row[name] = {"path": path.name, "sha256": digest(path)}
            records.append(row)
    manifest = root / "manifest.jsonl"
    manifest.write_text("".join(json.dumps(row) + "\n" for row in records))
    return manifest


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("directory", type=Path)
    parser.add_argument("--count", type=int, default=30)
    args = parser.parse_args()
    if args.count < 1:
        parser.error("Count must be positive")
    print(generate(args.directory, args.count))
